pub fn for_node_type(node_type: &str) -> Option<PlanReferenceEntry> {
    let key = match node_type {
        "Seq Scan" | "Parallel Seq Scan" => "seq_scan",
        "Index Scan" => "index_scan",
        "Index Only Scan" => "index_only_scan",
        "Bitmap Index Scan" => "bitmap_index_scan",
        "Bitmap Heap Scan" => "bitmap_heap_scan",
        value if value.starts_with("Nested Loop") => "nested_loop",
        value if value.contains("Hash Join") => "hash_join",
        value if value.contains("Merge Join") => "merge_join",
        "Hash" => "hash",
        "Sort" => "sort",
        "Incremental Sort" => "incremental_sort",
        "Aggregate" | "GroupAggregate" | "HashAggregate" => "aggregate",
        "Materialize" => "materialize",
        "Memoize" => "memoize",
        "Gather" => "gather",
        "Gather Merge" => "gather_merge",
        "Limit" => "limit",
        "Append" | "Merge Append" => "append",
        "CTE Scan" => "cte_scan",
        "Subquery Scan" => "subquery_scan",
        "Function Scan" => "function_scan",
        "WindowAgg" => "window_agg",
        "Unique" => "unique",
        "SetOp" => "setop",
        _ => return None,
    };

    // The text in `all()` depends on the active backend locale. Do not cache
    // the first language chosen for the entire lifetime of the application.
    all().into_iter().find(|entry| entry.key == key)
}

fn terms_for(key: &str) -> Vec<String> {
    let terms: &[&str] = match key {
        "seq_scan" => &[
            "scan",
            "heap",
            "relation",
            "predicate",
            "selectivity",
            "page_block",
            "plan_rows_actual_rows",
        ],
        "index_scan" => &[
            "scan",
            "index_lookup",
            "heap",
            "tuple_row",
            "predicate",
            "selectivity",
            "actual_loops",
            "index_cond_vs_filter",
        ],
        "index_only_scan" => &[
            "scan",
            "index_lookup",
            "heap",
            "tuple_row",
            "page_block",
            "plan_rows_actual_rows",
        ],
        "bitmap_index_scan" => &["scan", "index_lookup", "predicate", "page_block"],
        "bitmap_heap_scan" => &["scan", "heap", "page_block", "predicate"],
        "nested_loop" => &[
            "outer_input",
            "inner_input",
            "index_lookup",
            "actual_loops",
            "selectivity",
            "predicate",
            "plan_rows_actual_rows",
        ],
        "hash_join" => &[
            "build_side",
            "probe_side",
            "join_key",
            "predicate",
            "cardinality",
        ],
        "merge_join" => &["join_key", "predicate", "cardinality"],
        "hash" => &["build_side", "cardinality"],
        "materialize" => &["plan_node", "child_node", "actual_loops", "tuple_row"],
        "memoize" => &["inner_input", "index_lookup", "actual_loops"],
        "gather" | "gather_merge" => &["plan_node", "child_node", "plan_rows_actual_rows"],
        "limit" => &["plan_node", "child_node", "plan_rows_actual_rows"],
        "plan_rows_actual_rows" => &["plan_node", "actual_loops", "cardinality"],
        "actual_loops" => &["plan_node", "parent_node", "outer_input", "inner_input"],
        "index_cond_vs_filter" => &["predicate", "index_lookup", "selectivity"],
        "cardinality" => &["selectivity", "plan_rows_actual_rows"],
        "rows_removed" => &["predicate", "actual_loops", "selectivity"],
        _ => &[],
    };

    terms.iter().map(|value| (*value).into()).collect()
}

#[expect(
    clippy::too_many_arguments,
    reason = "existing call contract; refactor separately with callers"
)]
fn node(
    key: &str,
    title: &str,
    category: &str,
    short: &str,
    how_it_works: &str,
    good_when: &[&str],
    suspicious_when: &[&str],
    inspect: &[&str],
    misconceptions: &[&str],
    related: &[&str],
) -> PlanReferenceEntry {
    concept(
        key,
        title,
        category,
        short,
        how_it_works,
        good_when,
        suspicious_when,
        inspect,
        misconceptions,
        related,
        "https://www.postgresql.org/docs/current/using-explain.html",
    )
}

#[allow(clippy::too_many_arguments)]
fn concept(
    key: &str,
    title: &str,
    category: &str,
    short: &str,
    how_it_works: &str,
    good_when: &[&str],
    suspicious_when: &[&str],
    inspect: &[&str],
    misconceptions: &[&str],
    related: &[&str],
    docs_url: &str,
) -> PlanReferenceEntry {
    PlanReferenceEntry {
        key: key.into(),
        title: title.into(),
        category: category.into(),
        short: short.into(),
        how_it_works: how_it_works.into(),
        good_when: good_when.iter().map(|value| (*value).into()).collect(),
        suspicious_when: suspicious_when
            .iter()
            .map(|value| (*value).into())
            .collect(),
        inspect: inspect.iter().map(|value| (*value).into()).collect(),
        misconceptions: misconceptions.iter().map(|value| (*value).into()).collect(),
        related: related.iter().map(|value| (*value).into()).collect(),
        terms: terms_for(key),
        docs_url: docs_url.into(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn node_lookup_uses_the_current_reference_text() {
        let expected = all()
            .into_iter()
            .find(|entry| entry.key == "seq_scan")
            .unwrap();
        let actual = for_node_type("Seq Scan").unwrap();
        assert_eq!(actual.short, expected.short);
        assert_eq!(actual.how_it_works, expected.how_it_works);
        assert_eq!(actual.suspicious_when, expected.suspicious_when);
    }

    #[test]
    fn analyzer_reference_keys_exist() {
        let keys = all()
            .into_iter()
            .map(|entry| entry.key)
            .collect::<BTreeSet<_>>();
        // Each key is used as reference_key by a diagnostic in analyze.rs.
        for key in [
            "actual_loops",
            "bitmap_heap_scan",
            "cardinality",
            "hash",
            "heap_fetches",
            "index_cond_vs_filter",
            "jit",
            "limit",
            "memoize",
            "nested_loop",
            "parallel_workers",
            "repeated_scan",
            "rows_removed",
            "seq_scan",
            "sort",
            "temp_io",
        ] {
            assert!(keys.contains(key), "Missing reference for finding: {key}");
        }
    }

    #[test]
    fn reference_keys_are_unique() {
        let entries = all();
        let keys = entries
            .iter()
            .map(|entry| entry.key.as_str())
            .collect::<BTreeSet<_>>();

        assert_eq!(entries.len(), keys.len());
    }

    #[test]
    fn every_term_link_points_to_reference_entry() {
        let entries = all();
        let keys = entries
            .iter()
            .map(|entry| entry.key.as_str())
            .collect::<BTreeSet<_>>();

        for entry in &entries {
            for term in &entry.terms {
                assert!(
                    keys.contains(term.as_str()),
                    "{} references missing term {}",
                    entry.key,
                    term,
                );
            }
        }
    }

    #[test]
    fn nested_loop_links_foundational_terms() {
        let entry = all()
            .into_iter()
            .find(|entry| entry.key == "nested_loop")
            .unwrap();

        assert!(entry.terms.contains(&"outer_input".to_owned()));
        assert!(entry.terms.contains(&"inner_input".to_owned()));
        assert!(entry.terms.contains(&"selectivity".to_owned()));
    }
}
